#!/usr/bin/env bash
# Builds the game with every code plugin compiled in (dr:all_plugins), as
# it was before plugins were libraries: build/static/deimos. Not a release; the
# reference plugins:check compares the libraries against (D85), and a
# single binary to debug. Its own folder, so it finds no library beside it
# to load on top of what it has.
set -euo pipefail
cd "$(dirname "$0")/../.."
root=$DR_BUILD/plugin-roots/static
mkdir -p "$root" "$DR_BUILD/static"
{
	echo "package static_game"
	echo
	echo "// Generated by tools/plugins/static.sh: the game with every plugin compiled in."
	echo
	echo 'import "dr:game"'
	echo 'import _ "dr:all_plugins"'
	echo
	echo "main :: proc() {"
	echo "	game.main()"
	echo "}"
} > "$root/main.odin"
# shellcheck disable=SC2086 # DR_COLL and DR_LINK are word lists
odin build "$root" -out:"$DR_BUILD/static/deimos${DR_EXT:-}" $DR_COLL ${DR_LINK:-} -o:speed \
	-define:DR_VERSION="$(bash tools/version/version.sh)" ${ODIN_FLAGS:-}
[ -f "$DR_BUILD/static/deimos${DR_EXT:-}" ] || { echo "static: no binary built" >&2; exit 1; }
