#!/usr/bin/env bash
# Builds every code plugin as a shared library, plugins/<name>/<name>.so
# (.dll on Windows) under OUT, default $DR_BUILD/plugins, where the game
# beside it looks (game/plugin_libs.odin, decisions.md D85).
#
# A plugin's library is its packages (tools/plugins/packages.sh:
# plugins/<name>, and its view/ where it has one) and dr:plugin_entry,
# which exports what the game calls. Odin builds a library from one
# package, so each gets a root generated here that imports those and
# nothing else.
#
#   plugin_libs.sh [name ...]      every code plugin, or those named
#
# Takes the target from TARGET (windows_amd64 for a cross-check) and the
# usual DR_COLL, DR_LINK; extra Odin flags from ODIN_FLAGS (-debug). A
# plugin that draws nothing does not use RAYLIB_SHARED, hence
# -ignore-unused-defineables.
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=${OUT:-$DR_BUILD/plugins}
ROOTS=$DR_BUILD/plugin-roots
ext=.so
if [ "${OS:-}" = Windows_NT ] || [[ "${TARGET:-}" == windows* ]]; then ext=.dll; fi
# ABI= stamps the libraries otherwise: plugins:check builds one that the
# game must refuse.
ABI=${ABI:-$(bash tools/plugins/abi.sh)}

build_one() {
	local name=$1 root
	shift
	root=$ROOTS/$name
	mkdir -p "$root" "$OUT/$name"
	{
		echo "package ${name}_lib"
		echo
		echo "// Generated by tools/plugins/plugin_libs.sh: the root of $name's library."
		echo
		echo 'import _ "dr:plugin_entry"'
		for p in "$@"; do echo "import _ \"dr:$p\""; done
	} > "$root/lib.odin"
	# shellcheck disable=SC2086 # DR_COLL, DR_LINK and ODIN_FLAGS are word lists
	odin build "$root" -build-mode:shared -out:"$OUT/$name/$name$ext" $DR_COLL ${DR_LINK:-} \
		-o:speed -define:RAYLIB_SHARED=true -define:DR_ABI="$ABI" -ignore-unused-defineables \
		${TARGET:+-target:$TARGET} ${ODIN_FLAGS:-}
	[ -f "$OUT/$name/$name$ext" ] || { echo "plugin_libs: $name: no library built" >&2; return 1; }
	echo "plugin_libs: $name"
}

# Each library is a full compile of the core it carries; run them side by
# side, a few at a time. The list is read whole first: read from a process
# substitution, that process was a child too, and `wait -n` could return
# for it instead of a build, so the script once exited with the last
# library still being written (plugins:check failed a run in three, the
# stale library appearing two seconds after the game looked for it).
jobs=$(( $(nproc 2>/dev/null || echo 4) / 4 ))
[ "$jobs" -ge 1 ] || jobs=1
list=$(bash tools/plugins/packages.sh "$@")
failed=0
running=0
while read -r name pkgs; do
	[ -n "$name" ] || continue
	# shellcheck disable=SC2086 # pkgs is a word list
	build_one "$name" $pkgs &
	running=$((running + 1))
	if [ "$running" -ge "$jobs" ]; then
		wait -n || failed=1
		running=$((running - 1))
	fi
done <<<"$list"
while [ "$running" -gt 0 ]; do
	wait -n || failed=1
	running=$((running - 1))
done
exit $failed
